fn contains(ranges: []const Range, c: u21) bool {
    var lo: usize = 0;
    var hi = ranges.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        const r = ranges[mid];
        if (c < r.first) hi = mid else if (c > r.last) lo = mid + 1 else return true;
    }
    return false;
}
